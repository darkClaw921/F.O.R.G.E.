//! Готовый транскрипт беседы — общий стык плагина и ядра.
//!
//! Собирает его ПЛАГИН (у каждого мессенджера свой API истории и свой DTO
//! сообщения), а потребляет ядро: [`crate::prompt::build`] кладёт текст в
//! `<transcript>`, а [`crate::hub`] сохраняет [`Transcript::newest_id`] как
//! точку отсчёта следующего REFRESH. Поэтому сама структура живёт здесь: если
//! бы её объявлял каждый плагин, `prompt::build` пришлось бы делать generic
//! ради трёх одинаковых наборов из пяти полей.

/// Готовый транскрипт и всё, что о нём нужно знать вызывающему.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Transcript {
    /// Текст: по строке на сообщение, порядок по ВОЗРАСТАНИЮ id.
    pub text: String,
    /// Сколько сообщений реально попало в текст.
    pub messages_used: usize,
    /// Часть сообщений отброшена потолком символов.
    pub truncated: bool,
    /// Идентификатор самого старого сообщения В ТЕКСТЕ (не в выгрузке).
    pub oldest_id: Option<i32>,
    /// Идентификатор самого НОВОГО сообщения в тексте.
    ///
    /// Точка отсчёта инкрементального обновления: она уезжает в
    /// [`crate::prompts::ChatAnalysis::last_message_id`], а следующий REFRESH
    /// выгружает только то, что новее. Берётся из ТЕКСТА, а не из выгрузки:
    /// сохранить как «разобрано до» id сообщения, которое не попало в
    /// транскрипт, значило бы потерять его навсегда.
    pub newest_id: Option<i32>,
}
