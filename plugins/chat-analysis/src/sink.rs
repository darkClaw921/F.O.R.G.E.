//! Куда ядро вещает кадры анализа.
//!
//! Это ЕДИНСТВЕННАЯ развязка крейта от плагина. До выноса [`crate::hub`] знал
//! `VkServerMsg` и слал кадры прямо в broadcast VK — вместе с ним переехали бы
//! и WS-протокол VK, и его `broadcast`-канал, то есть Telegram получил бы
//! чужой enum кадров. Вместо этого ядро зовёт четыре метода, а плагин в
//! четыре строки перекладывает их в СВОЙ кадр (`VkServerMsg` / `TgServerMsg` /
//! `B24ServerMsg`) и вещает как ему удобно.
//!
//! # Почему методы синхронные
//!
//! Их зовёт пампер из своей таски, в том числе в горячем цикле дельт. Всякая
//! реализация, которую мы знаем, — это `broadcast::Sender::send`, то есть
//! мгновенная неблокирующая операция; сделать методы `async` значило бы
//! разрешить реализации ЖДАТЬ внутри пампера, а пампер ждать не имеет права:
//! пока он стои́т, копится буфер коалесцинга.
//!
//! # Порядок и обязательность кадров
//!
//! - [`AnalysisSink::started`] — ровно один, синхронно в
//!   [`crate::AnalysisHub::start`], ДО первой дельты;
//! - [`AnalysisSink::delta`] — ноль и больше, уже КОАЛЕСЦИРОВАННЫЕ ядром;
//! - [`AnalysisSink::error`] — ноль или один, всегда ПЕРЕД финальным кадром;
//! - [`AnalysisSink::done`] — ровно один на run, КРОМЕ отмены: после
//!   `AnalysisHub::cancel` финальный кадр шлёт сам плагин (пампер к этому
//!   моменту уже abort'нут и отправить ничего не может).

/// Приёмник кадров анализа.
pub trait AnalysisSink: Send + Sync + 'static {
    /// Анализ начался; размеры транскрипта уже известны.
    fn started(
        &self,
        run_id: &str,
        dialog_id: &str,
        kind: &str,
        messages_used: u32,
        truncated: bool,
    );

    /// Приращение ответа модели. Склеивается конкатенацией в порядке вызовов.
    fn delta(&self, run_id: &str, dialog_id: &str, text: &str);

    /// Run завершён: `ok == false` ⇒ `reason` объясняет, чем именно.
    fn done(
        &self,
        run_id: &str,
        dialog_id: &str,
        ok: bool,
        reason: Option<&str>,
        input_tokens: u64,
        output_tokens: u64,
    );

    /// Ошибка run'а — текст от раннера ЦЕЛИКОМ (в нём хвост stderr Claude CLI,
    /// единственный способ увидеть «CLI не залогинен», не читая логи сервера).
    fn error(&self, run_id: &str, dialog_id: &str, message: &str);
}
