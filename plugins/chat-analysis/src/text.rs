//! Мелкие текстовые и временны́е утилиты ядра.
//!
//! Их всего две, и обе живут здесь по одной причине: ими пользуются И ядро
//! (обрезка прошлого разбора в промпте, штампы времени пампера), И плагины
//! (превью реплик, `updated_at` в роутах). Вторая копия `truncate_chars` в
//! плагине разъехалась бы с этой ровно на кириллице — то есть на языке, на
//! котором написана каждая вторая заметка.

/// Обрезает строку по `max` СИМВОЛАМ (не байтам) и добавляет многоточие.
///
/// По символам, а не по байтам: срез `&s[..140]` на кириллице ПАНИКУЕТ (попал
/// в середину многобайтового символа), а «140 байт» превью — это 70 русских
/// букв, то есть половина обещанного.
#[must_use]
pub fn truncate_chars(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    let mut out: String = s.chars().take(max).collect();
    out.push('…');
    out
}

/// Текущее unix-время, секунды.
///
/// Через `SystemTime`, а не `chrono`: ядру ради одного штампа не нужна ни
/// временна́я зона, ни форматирование, а лишняя зависимость в листовом крейте
/// стоит дороже трёх строк. Часы «до эпохи» дают `0` — единственный разумный
/// ответ, паниковать на кривых часах машины ядру незачем.
#[must_use]
pub fn now_unix() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| i64::try_from(d.as_secs()).unwrap_or(i64::MAX))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Обрезка считает СИМВОЛЫ: байтовый срез рвал бы кириллицу и emoji.
    #[test]
    fn truncate_chars_counts_characters_not_bytes() {
        assert_eq!(truncate_chars("привет", 10), "привет");
        assert_eq!(truncate_chars("привет", 3), "при…");
        assert_eq!(truncate_chars("", 3), "");
        assert_eq!(truncate_chars("😀😀😀", 2), "😀😀…");
        let long: String = "я".repeat(500);
        assert_eq!(truncate_chars(&long, 140).chars().count(), 141, "+ многоточие");
    }

    #[test]
    fn now_unix_is_a_plausible_timestamp() {
        // Больше 2020 года и меньше 2100: проверяем не точность, а то, что
        // единица измерения — секунды, а не миллисекунды.
        let now = now_unix();
        assert!((1_577_836_800..4_102_444_800).contains(&now), "{now}");
    }
}
