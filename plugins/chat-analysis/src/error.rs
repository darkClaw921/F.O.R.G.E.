//! Ошибки ядра анализа.
//!
//! Крейт про HTTP не знает вовсе: он не выбирает код ответа и не строит
//! конверт ошибки — это делает плагин, у которого свой `ApiError` и своя
//! таблица кодов (у VK и Bitrix она даже записана в шапке `routes/mod.rs`).
//! Наружу отдаётся ЗАКРЫТЫЙ список причин, по которому плагин делает `match`
//! без разбора строк.

/// Почему анализ не начался (или не сохранился).
///
/// `PartialEq` — чтобы отказ проверялся в тестах сравнением, а не
/// `matches!` со свободным хвостом: `Busy(3)` и `Busy(2)` — разные ответы
/// пользователю.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum AnalysisError {
    /// Заняты ВСЕ слоты параллельных анализов другими беседами; внутри —
    /// сколько их идёт прямо сейчас. Отказ мгновенный: молчаливое ожидание на
    /// семафоре означало бы открытый попап без единого кадра и без объяснения.
    #[error("уже идёт {0} анализа(ов) по другим беседам")]
    Busy(usize),

    /// Бинаря Claude CLI по настроенному пути нет.
    ///
    /// Путь в текст НЕ включается: `Display` уходит в логи и в конверт ошибки,
    /// а путь — это кусок файловой системы машины. Плагину он известен и без
    /// нас ([`crate::AnalysisHub::cli_path`]), и он сам решает, показывать ли
    /// его пользователю (VK показывает: это его инструкция «поставьте CLI»).
    #[error("Claude CLI недоступен")]
    CliUnavailable,

    /// REFRESH без сохранённого разбора: обновлять нечего.
    #[error("сохранённого разбора нет")]
    NoPreviousAnalysis,

    /// Хранилище не прочиталось/не записалось. Внутри — уже обезличенное
    /// описание причины (ни путей, ни содержимого файла).
    #[error("хранилище недоступно: {0}")]
    Storage(String),
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `Display` не имеет права нести путь файла или токен: он попадает и в
    /// лог, и в тело ответа пользователю.
    #[test]
    fn display_leaks_neither_paths_nor_secrets() {
        let texts = [
            AnalysisError::Busy(2).to_string(),
            AnalysisError::CliUnavailable.to_string(),
            AnalysisError::NoPreviousAnalysis.to_string(),
            AnalysisError::Storage("диск переполнен".into()).to_string(),
        ];
        for t in &texts {
            assert!(!t.contains('/'), "путь в тексте ошибки: {t}");
            assert!(!t.is_empty());
        }
        assert!(texts[0].contains('2'), "число занятых слотов обязано быть видно");
    }
}
