//! Прогресс этапов и позиция в очереди.
//!
//! Реализуется в Ф5 вместе с пайплайном. Форма кадра уже зафиксирована —
//! [`crate::ws::protocol::MeetServerMsg::Progress`].
//!
//! **Очередь видна честно.** Ждущая расшифровка остаётся в статусе
//! `transcribing`, но кадр несёт `queued: true` и `queue_position`. Отдельного
//! статуса «в очереди» нет намеренно: он размножил бы таблицу переходов вдвое
//! ради информации, которая по природе своей временная, — и каждый новый
//! этап пайплайна требовал бы второго статуса-близнеца.
