//! Пост-обработка: ffmpeg, модели, whisper, атрибуция спикеров, рендер.
//!
//! Модуль НЕ импортирует `axum` и `http`.
//!
//! Реализуется в Ф5 (`forge-meet-f5-s854`). Решения, зафиксированные заранее,
//! потому что каждое стоило измерения:
//!
//! **whisper НЕ ЗАПУСКАЕТСЯ, пока идёт запись.** Chrome рендерит встречу на
//! том же GPU и будет получать дропы. Расшифровка стартует только после
//! закрытия браузера.
//!
//! **Правило «только GPU» исполняется структурно.** `-ng`/`--no-gpu` никогда
//! не попадает в argv (юнит-тест на чистую `build_args`), а stderr парсится на
//! ТОЧНЫЙ префикс `ggml_metal_init:` в начале строки. Проверка
//! `contains("ggml_metal")` НЕ ГОДИТСЯ: `ggml_metal_device_init:` и
//! `ggml_metal_library_init:` печатаются всегда, даже с `-ng` и даже на
//! `--help`. Цена нарушения измерена в Ф0: те же 20 секунд аудио считаются 14
//! секунд на GPU и 0,7× реального времени на CPU — разрыв по энкоду
//! пятнадцатикратный, час аудио на CPU это почти полтора часа.
//!
//! **`amix=...:normalize=0`.** Дефолт `normalize=1` делит на число входов, и
//! при пяти треках всё становится в пять раз тише, что реально бьёт по
//! распознаванию. На это есть регресс-тест golden-строки фильтрографа.
//!
//! **`--vad` без `-vm`** роняет whisper 1.9.2 по SIGABRT (exit 134), не
//! сообщая об ошибке (измерено в Ф0). Поэтому модель silero — отдельный
//! элемент реестра моделей, а `build_args` не имеет права собрать `--vad` без
//! `-vm`.
//!
//! **`attribute_segments` работает В ОБОИХ режимах.** Для Телемоста трек не
//! соответствует человеку (`Slots`, измерено), поэтому интервалы приходят из
//! DOM, а не из пер-трекового VAD. Ветка «трек = человек» не может быть
//! единственной ни в одном месте пайплайна.
//!
//! ## Состав модуля
//!
//! | подмодуль | что делает |
//! |---|---|
//! | [`proc`] | запуск внешних процессов: таймаут, убийство, ХВОСТ STDERR пользователю |
//! | [`ffmpeg`] | фильтрограф, архивный микс, длительность по `ffprobe` |
//! | [`whisper`] | `build_args` и структурный Metal-гард |
//! | [`speakers`] | интервалы речи, атрибуция сегментов, коррекция таймлайна |
//! | [`pertrack`] | нарезка дорожек по VAD и расшифровка по одной — режим `PerParticipant` |
//! | [`render`] | `transcript.json` и `transcript.md` |
//! | [`run`] | сквозной прогон: сведение → архив → дрейф → очередь → whisper → атрибуция → рендер |

pub mod ffmpeg;
pub mod pertrack;
pub mod proc;
pub mod run;
pub mod render;
pub mod speakers;
pub mod whisper;

/// Подкаталог транзитных файлов внутри каталога встречи.
///
/// Всё, что можно пересчитать: сведённый `mix.wav`, вывод whisper. Чистится
/// после успешного прохода пайплайна — но НЕ раньше, чем расшифровка забрала
/// оттуда свой вход.
pub const WORK_DIR: &str = "work";

/// Имя сведённого файла, который уходит в whisper.
pub const MIX_WAV: &str = "mix.wav";

/// Имя архивного аудиофайла встречи.
///
/// `.m4a`, а не `.wav`: 115 МБ на час убьют плеер в браузере, потому что
/// фронт грузит аудио через `fetch` + `blob:` (у элемента `audio` нет
/// Bearer-токена). AAC 32 кбит/с даёт 14 МБ на час, и на такой величине blob
/// перематывается идеально.
///
/// Именно поэтому whisper получает НЕ этот файл: whisper.cpp принимает
/// `flac`, `mp3`, `ogg` и `wav` (измерено в Ф0), а `m4a` — нет.
pub const ARCHIVE_AUDIO: &str = "audio.m4a";

/// Имя файла машинной расшифровки.
pub const TRANSCRIPT_JSON: &str = "transcript.json";

/// Имя файла человекочитаемой расшифровки.
pub const TRANSCRIPT_MD: &str = "transcript.md";
