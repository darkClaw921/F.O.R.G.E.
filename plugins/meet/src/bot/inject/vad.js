/*
 * ДЕТЕКТ РЕЧИ (VAD) — чистая логика.
 *
 * Модуль ES: его импортирует `node --test`, и он же встраивается в worklet
 * (сборщик снимает слово `export` со строк с маркером — в
 * `AudioWorkletGlobalScope` модулей нет).
 *
 * ПОЧЕМУ VAD ЖИВЁТ В AudioWorkletProcessor, А НЕ В setInterval
 *
 * Окно бота стоит свёрнутым либо за экраном, то есть occluded, а Chrome
 * троттлит таймеры рендерера occluded-окна ДО ОДНОЙ СЕКУНДЫ. Пятидесятимилли-
 * секундный цикл детекта на `setInterval` в таком окне просто разваливается:
 * вместо двадцати замеров в секунду приходит один, границы речи съезжают на
 * сотни миллисекунд, и атрибуция спикеров едет вместе с ними.
 *
 * Worklet работает в АУДИОПОТОКЕ. Он не подвержен троттлингу в принципе, а
 * его тайминг сэмпл-точен: каждый вызов `process` — ровно 128 сэмплов, и
 * время считается их количеством, а не часами. Три флага
 * `--disable-*-throttling` остаются вторым эшелоном, но структурное решение —
 * именно worklet.
 *
 * ЧЕТЫРЕ ПАРАМЕТРА — ИЗ КОНФИГА, А НЕ КОНСТАНТЫ
 *
 * Порог включения, порог выключения, подтверждение и hangover невозможно
 * вывести из первых принципов: их подбирают по живым записям. Константа
 * означала бы пересборку и релиз ради подстройки числа.
 *
 * СДВИГ НАЗАД — САМОЕ ВАЖНОЕ ЗДЕСЬ
 *
 * Речь объявляется начавшейся только после `confirmMs` непрерывного
 * превышения порога — иначе каждый щелчок был бы репликой. Но НАЧАЛАСЬ она
 * на `confirmMs` раньше, и момент перехода обязан эмититься со сдвигом
 * назад. Без сдвига ВСЕ интервалы речи систематически съезжают вправо на
 * длину подтверждения, а вместе с ними — и границы, по которым режется
 * транскрипт.
 *
 * Симметрично устроен и конец: речь считается продолжающейся ещё `hangoverMs`
 * после падения ниже порога (пауза между словами — не конец реплики), но
 * закончилась она в момент падения, и сдвиг назад применяется тот же.
 */

/** Значения по умолчанию. Совпадают с дефолтами `MeetConfig`. */
export const VAD_DEFAULTS = { // FORGE_STRIP_FOR_WORKLET
  onDb: 12,
  offDb: 6,
  confirmMs: 120,
  hangoverMs: 500,
  // Стартовый шумовой пол. Нарочно очень низкий: реальный пол он найдёт за
  // первые же кадры тишины, а завышенный старт «съел» бы начало первой
  // реплики.
  initialFloorDb: -70,
  // Скорость подстройки пола ВВЕРХ (шум вырос) и ВНИЗ (стало тише).
  // Вверх — медленно, иначе пол уползёт за громкой речью и детект ослепнет.
  // Вниз — быстро, чтобы после громкого участка не пропустить тихую реплику.
  floorRisePerSec: 6,
  floorFallPerSec: 60
};

/**
 * Создаёт детектор для ОДНОЙ дорожки.
 *
 * Состояние держится внутри замыкания: у каждой дорожки свой шумовой пол,
 * и общий на всех был бы прямой ошибкой — участник с шумной гарнитурой
 * поднял бы порог всем остальным.
 */
export function createVadDetector(options) { // FORGE_STRIP_FOR_WORKLET
  const cfg = Object.assign({}, VAD_DEFAULTS, options || {});

  let floorDb = cfg.initialFloorDb;
  let speaking = false;
  // Сколько миллисекунд подряд уровень держится выше/ниже порога.
  let aboveMs = 0;
  let belowMs = 0;
  // Видел ли детектор хоть один замер.
  //
  // ПЕРВЫЙ ЗАМЕР ЗАДАЁТ ПОЛ ЦЕЛИКОМ, и это не оптимизация, а исправление
  // настоящей поломки. Пол, ползущий от -70 дБ со скоростью нескольких
  // децибел в секунду, доберётся до реального шума комнаты (-40…-60 дБ)
  // только через десятки секунд. Всё это время порог ВЫКЛЮЧЕНИЯ
  // (`пол + 6 дБ`) лежит НИЖЕ уровня самой тишины — то есть речь, однажды
  // начавшись, не кончается никогда, и вся встреча становится одной
  // репликой. Ровно это и поймал тест полного прохода по расписанию
  // мок-встречи.
  //
  // Обратный риск — первый замер попал на речь — самоисправляется: пол
  // падает со скоростью `floorFallPerSec`, то есть за доли секунды.
  let seeded = false;

  return {
    /**
     * Скармливает очередной замер уровня.
     *
     * @param {number} levelDb уровень блока в дБ;
     * @param {number} nowMs   конец блока на общей оси времени;
     * @param {number} dtMs    длительность блока.
     * @returns {null|{on: boolean, at: number}} момент перехода СО СДВИГОМ
     *          НАЗАД либо `null`, если ничего не изменилось.
     */
    push(levelDb, nowMs, dtMs) {
      if (!seeded) {
        seeded = true;
        floorDb = levelDb;
      }
      const onThreshold = floorDb + cfg.onDb;
      const offThreshold = floorDb + cfg.offDb;
      let event = null;

      if (!speaking) {
        if (levelDb > onThreshold) {
          aboveMs += dtMs;
          if (aboveMs >= cfg.confirmMs) {
            speaking = true;
            belowMs = 0;
            // СДВИГ НАЗАД: речь началась там, где уровень впервые превысил
            // порог, а не там, где мы в этом убедились.
            event = { on: true, at: Math.max(0, nowMs - cfg.confirmMs) };
          }
        } else {
          aboveMs = 0;
        }
      } else {
        if (levelDb < offThreshold) {
          belowMs += dtMs;
          if (belowMs >= cfg.hangoverMs) {
            speaking = false;
            aboveMs = 0;
            // Тот же сдвиг: hangover продлевает реплику, чтобы не рвать её
            // на паузах между словами, но КОНЧИЛАСЬ она в момент падения.
            event = { on: false, at: Math.max(0, nowMs - cfg.hangoverMs) };
          }
        } else {
          belowMs = 0;
        }
      }

      // Шумовой пол подстраивается ТОЛЬКО пока уровень НИЖЕ порога включения.
      //
      // Условия «не говорим» здесь мало, и это стоило отдельного теста:
      // между превышением порога и подтверждением речи проходит `confirmMs`,
      // и всё это время пол успевал подползти вверх на доли децибела. За одну
      // реплику — мелочь, за сотню реплик встречи — десятки децибел, после
      // которых детект слепнет полностью. Поэтому адаптация выключается в тот
      // же момент, когда уровень поднялся выше порога, а не когда мы в этом
      // убедились.
      if (!speaking && aboveMs === 0) {
        const step = (dtMs / 1000) * (levelDb > floorDb ? cfg.floorRisePerSec : cfg.floorFallPerSec);
        if (levelDb > floorDb) {
          floorDb = Math.min(levelDb, floorDb + step);
        } else {
          floorDb = Math.max(levelDb, floorDb - step);
        }
      }

      return event;
    },

    /** Идёт ли речь прямо сейчас. */
    isSpeaking() {
      return speaking;
    },

    /** Текущий адаптивный шумовой пол, дБ. Нужен диагностике и тестам. */
    floor() {
      return floorDb;
    },

    /**
     * Закрывает незакрытый интервал в конце записи.
     *
     * Без этого последняя реплика встречи, оборванная выходом бота, не имела
     * бы конца — и весь хвост транскрипта достался бы одному спикеру.
     */
    finish(nowMs) {
      if (!speaking) {
        return null;
      }
      speaking = false;
      return { on: false, at: nowMs };
    }
  };
}

/**
 * Слияние сырых переходов в интервалы.
 *
 * Живёт здесь, а не в Rust, ровно по одной причине: тестировать её удобнее
 * рядом с самим детектом, а вход у неё тот же — поток `{on, at}`.
 * Незакрытый интервал в конце закрывается временем окончания записи.
 */
export function intervalsFromEvents(events, endMs) { // FORGE_STRIP_FOR_WORKLET
  const out = [];
  let open = null;
  for (const e of events) {
    if (e.on) {
      // Дубль `on` при уже открытом интервале — не ошибка входа, а
      // последствие переподключения дорожки. Первый выигрывает.
      if (open === null) { open = e.at; }
    } else if (open !== null) {
      if (e.at > open) { out.push({ start_ms: open, end_ms: e.at }); }
      open = null;
    }
  }
  if (open !== null && endMs > open) {
    out.push({ start_ms: open, end_ms: endMs });
  }
  return out;
}
