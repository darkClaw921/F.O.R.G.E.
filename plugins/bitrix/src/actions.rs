//! Троттлинг ЧАСТЫХ клиентских действий: отметка о прочтении и «печатает…».
//!
//! # Зачем это на сервере, а не только во фронте
//!
//! Оба действия порождаются не кнопкой, а ЖЕСТОМ: прокруткой ленты и набором
//! текста. Браузер шлёт их десятками в секунду, а бюджет портала — 2 запроса в
//! секунду на весь плагин ([`crate::api::throttle`]). Один пользователь,
//! листающий историю, способен выесть его целиком, и тогда встанет всё
//! остальное: список диалогов, страницы истории, отправка.
//!
//! Фронт тоже троттлит (иначе он гонял бы сеть впустую), но полагаться на это
//! нельзя: панель открыта в нескольких вкладках, кэш PWA держит старую версию
//! модулей неделями, а devforge в remote-mode отвечает нескольким браузерам
//! сразу. Сервер — единственное место, где ограничение общее.
//!
//! # ПЕРЕДНИЙ ФРОНТ, а не задний
//!
//! Первый вызов в окне УХОДИТ В ПОРТАЛ немедленно, последующие подавляются:
//!
//! ```text
//!   вызовы:  │▌▌▌▌▌▌▌▌▌▌      ▌▌▌▌
//!   в портал: ▌               ▌
//!             └── 800 мс ──┘
//! ```
//!
//! Задний фронт (классический debounce — «подождать тишины и отправить
//! последний») дал бы более точный `MESSAGE_ID`, но ценой отложенной задачи на
//! каждый диалог и задержки в те же 800 мс перед обнулением счётчика. Для
//! прочтения это заметно: пользователь долистал до низа, а бейдж ещё горит.
//! Передний фронт гасит счётчик сразу, а потеря последнего идентификатора
//! внутри окна безопасна — `im.dialog.read` без `MESSAGE_ID` читает диалог
//! целиком, и следующее же событие ленты повторит отметку.
//!
//! # Ключ — диалог
//!
//! Окно считается ОТДЕЛЬНО на каждый диалог: чтение одного чата не должно
//! отменять отметку в соседнем, иначе быстрое переключение по колонке оставляло
//! бы непрочитанным то, что пользователь уже открыл.

use std::collections::HashMap;
use std::sync::Mutex;

/// Окно отметки о прочтении, миллисекунды.
///
/// Восемьсот — компромисс, снятый с поведения ленты: прокрутка порождает
/// события каждые ~16 мс, то есть без окна одно листание диалога стоило бы
/// десятков запросов. Меньше 500 мс окно перестаёт ловить инерционную
/// прокрутку трекпада, больше секунды — пользователь успевает заметить, что
/// счётчик не гаснет.
pub const READ_DEBOUNCE_MS: i64 = 800;

/// Окно индикатора «печатает…», миллисекунды.
///
/// Восемь секунд — из поведения самого портала: индикатор в его веб-клиенте
/// живёт около десяти секунд, поэтому обновлять его чаще бессмысленно, а реже
/// — значит дать ему погаснуть посреди набора длинного сообщения.
pub const TYPING_INTERVAL_MS: i64 = 8_000;

/// Сколько ключей помнит один троттлер.
///
/// Ключей ровно столько, сколько диалогов трогал пользователь за сессию, — но
/// карта без потолка это утечка на длинном аптайме, а забытая запись стоит
/// ровно одного лишнего запроса к порталу.
pub const MAX_TRACKED_KEYS: usize = 512;

/// Через сколько запись считается протухшей и выметается, миллисекунды.
///
/// Минута перекрывает оба окна с большим запасом: запись старше неё уже не
/// может никого подавить.
pub const KEY_TTL_MS: i64 = 60_000;

/// Ограничитель частоты вызовов по ключу.
///
/// Синхронный `std::sync::Mutex`, а не `tokio::Mutex`: внутри нет ни одного
/// `await`, а брать асинхронный мьютекс ради вставки в `HashMap` значило бы
/// платить точкой планирования на каждый кадр прокрутки.
#[derive(Debug, Default)]
pub struct RateGate {
    /// Ключ → момент последнего ПРОПУЩЕННОГО вызова, миллисекунды.
    last: Mutex<HashMap<String, i64>>,
}

impl RateGate {
    /// Пустой троттлер.
    pub fn new() -> Self {
        Self::default()
    }

    /// Пропустить ли вызов ключа `key` в момент `now_ms`.
    ///
    /// Возвращает `true` и запоминает момент, если с прошлого пропущенного
    /// вызова прошло не меньше `interval_ms`; иначе `false` и состояние не
    /// меняется.
    ///
    /// Время приходит ПАРАМЕТРОМ, а не берётся из часов: иначе тест на окно в
    /// восемь секунд обязан был бы спать восемь секунд.
    ///
    /// # Panics
    ///
    /// Не паникует: отравленный мьютекс распаковывается вместе с содержимым —
    /// худшее, что может случиться с троттлером, это лишний запрос к порталу,
    /// и ронять из-за этого запрос пользователя нельзя.
    pub fn allow(&self, key: &str, now_ms: i64, interval_ms: i64) -> bool {
        let mut map = match self.last.lock() {
            Ok(guard) => guard,
            Err(poisoned) => poisoned.into_inner(),
        };
        if let Some(prev) = map.get(key) {
            // `now < prev` означает, что часы системы отпрыгнули назад
            // (перевод времени, синхронизация NTP). Тогда окно считается
            // истёкшим: держать пользователя до тех пор, пока часы догонят
            // прошлое, — худший из вариантов.
            if now_ms >= *prev && now_ms - *prev < interval_ms {
                return false;
            }
        }
        if map.len() >= MAX_TRACKED_KEYS {
            map.retain(|_, at| now_ms.saturating_sub(*at) < KEY_TTL_MS);
        }
        map.insert(key.to_string(), now_ms);
        true
    }

    /// Забывает ключ — следующий вызов пройдёт немедленно.
    ///
    /// Нужен смене диалога: открыв чат, пользователь ждёт, что счётчик
    /// погаснет сразу, а не через остаток чужого окна.
    pub fn forget(&self, key: &str) {
        match self.last.lock() {
            Ok(mut map) => {
                map.remove(key);
            }
            Err(poisoned) => {
                poisoned.into_inner().remove(key);
            }
        }
    }

    /// Сколько ключей помнит троттлер (диагностика и тесты).
    pub fn len(&self) -> usize {
        match self.last.lock() {
            Ok(map) => map.len(),
            Err(poisoned) => poisoned.into_inner().len(),
        }
    }

    /// Пуст ли троттлер.
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }
}

/// Текущее время в миллисекундах — единственный источник для роутов.
pub fn now_ms() -> i64 {
    chrono::Utc::now().timestamp_millis()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// ПЕРЕДНИЙ ФРОНТ: первый вызов проходит, остальные в окне — нет.
    #[test]
    fn the_first_call_in_a_window_passes_and_the_rest_are_dropped() {
        let gate = RateGate::new();
        assert!(gate.allow("chat27", 1_000, READ_DEBOUNCE_MS));
        // Десять кадров прокрутки подряд — ни одного запроса к порталу.
        for step in 1..=10 {
            assert!(
                !gate.allow("chat27", 1_000 + step * 16, READ_DEBOUNCE_MS),
                "кадр {step} обязан быть подавлен"
            );
        }
        // Ровно на границе окно уже истекло.
        assert!(gate.allow("chat27", 1_000 + READ_DEBOUNCE_MS, READ_DEBOUNCE_MS));
        // …и следующее окно отсчитывается от НЕГО, а не от первого вызова.
        assert!(!gate.allow("chat27", 1_000 + READ_DEBOUNCE_MS + 1, READ_DEBOUNCE_MS));
    }

    /// Окна диалогов независимы: чтение одного чата не глушит соседний.
    #[test]
    fn windows_are_counted_per_dialog() {
        let gate = RateGate::new();
        assert!(gate.allow("chat27", 0, READ_DEBOUNCE_MS));
        assert!(gate.allow("19", 0, READ_DEBOUNCE_MS), "соседний диалог");
        assert!(gate.allow("sg12", 10, READ_DEBOUNCE_MS));
        assert!(!gate.allow("chat27", 10, READ_DEBOUNCE_MS));
        assert_eq!(gate.len(), 3);
    }

    /// «Печатает…» живёт по своему окну — восемь секунд.
    #[test]
    fn typing_uses_its_own_eight_second_window() {
        let gate = RateGate::new();
        assert!(gate.allow("chat27", 0, TYPING_INTERVAL_MS));
        // Быстрый набор: события идут каждые 100 мс — в портал не уходит ничего.
        for step in 1..=70 {
            assert!(!gate.allow("chat27", step * 100, TYPING_INTERVAL_MS));
        }
        assert!(gate.allow("chat27", TYPING_INTERVAL_MS, TYPING_INTERVAL_MS));
    }

    /// Открытие диалога сбрасывает окно: счётчик обязан гаснуть сразу.
    #[test]
    fn forgetting_a_key_reopens_the_window() {
        let gate = RateGate::new();
        assert!(gate.allow("chat27", 0, READ_DEBOUNCE_MS));
        assert!(!gate.allow("chat27", 100, READ_DEBOUNCE_MS));
        gate.forget("chat27");
        assert!(gate.allow("chat27", 100, READ_DEBOUNCE_MS));
        // Забвение неизвестного ключа — не ошибка.
        gate.forget("нет-такого");
    }

    /// Часы, отпрыгнувшие назад, не запирают пользователя до конца суток.
    #[test]
    fn a_backwards_clock_does_not_lock_the_gate() {
        let gate = RateGate::new();
        assert!(gate.allow("chat27", 10_000, READ_DEBOUNCE_MS));
        assert!(
            gate.allow("chat27", 5_000, READ_DEBOUNCE_MS),
            "перевод часов назад обязан открывать окно, а не закрывать его"
        );
    }

    /// Карта не растёт бесконечно: на потолке протухшие записи выметаются.
    #[test]
    fn the_key_map_has_a_ceiling() {
        let gate = RateGate::new();
        for i in 0..MAX_TRACKED_KEYS {
            assert!(gate.allow(&format!("chat{i}"), 0, READ_DEBOUNCE_MS));
        }
        assert_eq!(gate.len(), MAX_TRACKED_KEYS);

        // Спустя две минуты все прежние записи протухли — уборка оставляет
        // только новую.
        assert!(gate.allow("свежий", 2 * KEY_TTL_MS, READ_DEBOUNCE_MS));
        assert_eq!(gate.len(), 1, "протухшие ключи обязаны вымететься");
    }

    /// Часы отдают миллисекунды и идут вперёд — на них держатся оба окна.
    #[test]
    fn the_clock_is_in_milliseconds() {
        let a = now_ms();
        assert!(a > 1_700_000_000_000, "часы отдают не миллисекунды: {a}");
        assert!(now_ms() >= a);
    }
}
