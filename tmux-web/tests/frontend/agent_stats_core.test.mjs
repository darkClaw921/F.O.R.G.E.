const timers = {callbacks:new Set(),setInterval(cb){this.callbacks.add(cb);return cb;},clearInterval(cb){this.callbacks.delete(cb);}};
const pending=[],drawn=[],errors=[]; let filter='old';
const poll=createPoller({timers,getQuery:()=>({filter}),load:q=>new Promise((resolve,reject)=>pending.push({q,resolve,reject})),onData:d=>drawn.push(d),onError:e=>errors.push(e)});
poll.show(); assert.equal(timers.callbacks.size,1); assert.equal(pending.length,1);
await poll.refresh(); assert.equal(pending.length,1,'a slow request does not duplicate on a tick');
filter='new'; poll.change(); assert.equal(pending.length,2);
pending[1].resolve('new'); await new Promise(r=>setImmediate(r));
pending[0].resolve('old'); await new Promise(r=>setImmediate(r));
assert.deepEqual(drawn,['new'],'stale filter results never draw');
poll.refresh(); poll.hide(); pending[2].reject(new Error('late failure')); await new Promise(r=>setImmediate(r));
assert.equal(timers.callbacks.size,0); assert.deepEqual(errors,[],'hidden view ignores stale errors');
await poll.refresh(); assert.equal(pending.length,3,'hidden view sends no requests');
poll.show(); assert.equal(timers.callbacks.size,1); pending[3].resolve('reopened'); await new Promise(r=>setImmediate(r)); poll.hide();
assert.deepEqual(drawn,['new','reopened']);

