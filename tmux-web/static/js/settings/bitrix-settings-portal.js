// tmux-web / настройки — какой ПОРТАЛ Битрикс24 сейчас правит вкладка настроек.
//
// Порталов у панели может быть несколько, и белый список с скоупом авторазбора
// у каждого свой (`bitrix_portal_prefs`, см. шапку `js/bitrix/visibility.js`).
// Значит у вкладки настроек появляется вопрос, которого у соседних панелей нет
// вовсе: НАСТРОЙКИ КАКОГО ПОРТАЛА сейчас видны и куда уйдёт сохранение.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ КРОШЕЧНЫЙ МОДУЛЬ, А НЕ ПОЛЕ В ФОРМЕ. Ответ нужен ДВУМ
// независимым формам вкладки: «Видимость диалогов»
// (`bitrix-visibility-tab.js`, там же и сам переключатель) и «Голосовые
// сообщения» (`voice-tab.js` через `voice-scope-sources.js`). Вторая — общий на
// три панели модуль, который про Битрикс не знает ничего и знать не должен;
// передать значение через него было бы возможно только протащив портал сквозь
// чужой контракт.
//
// ПОЧЕМУ НЕ АКТИВНЫЙ ПОРТАЛ ПАНЕЛИ (`js/bitrix/api.js::activePortal`). Потому
// что это разные вопросы: панель ОТКРЫТА на одном портале, а настраивать
// человек может любой — ровно ради этого переключатель и добавлен. Умолчание
// при этом активный портал: настройки почти всегда открывают «про то, что
// сейчас на экране».
//
// ВРЕМЯ ЖИЗНИ. Значение живёт столько же, сколько открытая модалка: закрытие
// вкладки настроек его не стирает намеренно — человек, вернувшийся в настройки,
// продолжает с того портала, который правил.

import { activePortal } from '../bitrix/api.js';

const local = {
    /** Явно выбранный портал; пусто ⇒ активный портал панели. */
    chosen: '',
};

/**
 * Портал, чьи настройки сейчас правит вкладка.
 *
 * @returns {string} `portal_id` либо пустая строка (порталов ещё нет)
 */
export function settingsPortal() {
    return local.chosen || String(activePortal() || '');
}

/**
 * Выбрать портал в форме настроек.
 *
 * @param {string} portalId — пусто возвращает умолчание (активный портал)
 */
export function setSettingsPortal(portalId) {
    local.chosen = String(portalId == null ? '' : portalId).trim();
}
